import { apiClient, liveFirst } from "../../services/apiClient";
import { clonePhase6Data } from "../../mocks/phase6MockData";

let store=clonePhase6Data();
const wait=(ms=120)=>new Promise(r=>setTimeout(r,ms));

export const reportsApi={
  async getOverview(params={}){
    return liveFirst(
      async () => {
        const {data}=await apiClient.get("/api/v1/reports/overview",{params});return data;
      },
      async () => {
        await wait();
        return {bookings:86,revenue:1840000,leads:48,conversion:18.75,months:store.reports.months,channels:store.reports.channels};
      }
    );
  },
  async exportCsv(report,params={}){
    return liveFirst(
      async () => {
        const {data}=await apiClient.get(`/api/v1/reports/${report}/export`,{params,responseType:"blob"});return data;
      },
      async () => {
        await wait();
        return {downloadUrl:null,report,params,message:"Mock export generated by UI layer."};
      }
    );
  }
};
