/**
 * Returns countries organized with priority destinations at the top,
 * followed by the rest sorted alphabetically.
 */
export const getSortedBillingCountries = () => {
  const priorityMap = new Map();
  PRIORITY_COUNTRY_CODES.forEach((code, index) => priorityMap.set(code, index));

  const priorityList = [];
  const otherList = [];

  WORLD_COUNTRIES.forEach((c) => {
    if (priorityMap.has(c.code)) {
      priorityList.push(c);
    } else {
      otherList.push(c);
    }
  });

  priorityList.sort(
    (a, b) => priorityMap.get(a.code) - priorityMap.get(b.code),
  );
  otherList.sort((a, b) => a.name.localeCompare(b.name));

  return [...priorityList, ...otherList];
};

/**
 * Finds a country by 2-letter alpha code. Defaults to India if not found.
 */
export const getBillingCountryByCode = (code = "IN") => {
  if (!code) return { name: "India", code: "IN", flag: "🇮🇳" };
  const target = code.trim().toUpperCase();
  const match = WORLD_COUNTRIES.find((c) => c.code === target);
  return match || { name: "India", code: "IN", flag: "🇮🇳" };
};

