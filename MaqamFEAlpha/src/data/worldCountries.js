/**
 * Detects the user's current country using fast IP geolocation with timezone fallback.
 * @returns {Promise<{ name: string, code: string, flag: string }>}
 */
export const detectUserCountry = async () => {
  // 1. Try IP-based country detection (fast & accurate for international users)
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2500);

    const res = await fetch("https://api.country.is", {
      signal: controller.signal,
    });
    clearTimeout(timeoutId);

    if (res.ok) {
      const data = await res.json();
      if (data?.country && typeof data.country === "string") {
        return getBillingCountryByCode(data.country);
      }
    }
  } catch (err) {
    // Silent fallback to timezone detection
  }

  // 2. Timezone-based heuristic fallback
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone.toLowerCase();
    if (TIMEZONE_COUNTRY_MAP[tz]) {
      return getBillingCountryByCode(TIMEZONE_COUNTRY_MAP[tz]);
    }

    for (const [key, code] of Object.entries(TIMEZONE_COUNTRY_MAP)) {
      if (tz.includes(key)) {
        return getBillingCountryByCode(code);
      }
    }
  } catch (_) {
    // Ignore error
  }

  // 3. Ultimate default: India
  return { name: "India", code: "IN", flag: "🇮🇳" };
};

